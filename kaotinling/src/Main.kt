fun main() {
    // 实验 1：字符串
    println("你好，Kotlin")
    println("Hello World")

    // 实验 2：拼接
    println("第" + 1 + "周")
    println("1 + 2 = " + (1 + 2))

    // 实验 3：多行
    println("第一行")
    println("第二行")
    print("这行不换行")
    print("所以接在上一行后面\n")

    // 实验 4：转义
    println("制表符\t左边\t右边")
    println("引号要说：\"引用的字\"")
    println("反斜杠：\\")
    println("一个 println 也能出两行\n第二行在这里")

    // 实验 5：数字计算
    println(1 + 2)
    println(10 / 3)
    println(10.0 / 3)
    println(10 % 3)
}